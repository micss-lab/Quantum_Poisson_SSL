def _standardize(X):
    return (X - X.mean(0)) / (X.std(0) + 1e-12)


def load_iris():
    from sklearn.datasets import load_iris as _l
    d = _l()
    return _standardize(d.data.astype(np.float64)), d.target


def load_wine():
    from sklearn.datasets import load_wine as _l
    d = _l()
    return _standardize(d.data.astype(np.float64)), d.target


def load_breast_cancer():
    from sklearn.datasets import load_breast_cancer as _l
    d = _l()
    return _standardize(d.data.astype(np.float64)), d.target


def load_heart():
    """Heart Disease (Statlog) via OpenML.               [FLAG loader]"""
    from sklearn.datasets import fetch_openml
    d = fetch_openml(name="heart-statlog", version=1, as_frame=False)
    X = d.data.astype(np.float64)
    classes = {c: i for i, c in enumerate(np.unique(d.target))}
    y = np.array([classes[c] for c in d.target])
    return _standardize(X), y


def load_german():
    """German Credit (credit-g) via OpenML; categorical features
    one-hot encoded, then standardized.                  [FLAG loader]"""
    from sklearn.datasets import fetch_openml
    import pandas as pd
    d = fetch_openml(name="credit-g", version=1, as_frame=True)
    X = pd.get_dummies(d.data).to_numpy(dtype=np.float64)
    classes = {c: i for i, c in enumerate(np.unique(d.target))}
    y = np.array([classes[c] for c in d.target])
    return _standardize(X), y


def load_optdigits(data_dir="./data"):
    """UCI Optdigits (n=5620, d=64, C=10) via local .tra/.tes files
    if present in data_dir, else OpenML.

    Note: sklearn's load_digits() is only the 1797-sample test subset
    of Optdigits -- do not use it here; the protocol runs on the full
    5620-sample set (union of optdigits.tra, 3823 samples, and
    optdigits.tes, 1797 samples)."""
    tra = os.path.join(data_dir, "optdigits.tra")
    tes = os.path.join(data_dir, "optdigits.tes")
    if os.path.exists(tra) and os.path.exists(tes):
        a = np.loadtxt(tra, delimiter=",")
        b = np.loadtxt(tes, delimiter=",")
        M = np.vstack([a, b])
        X, y = M[:, :-1], M[:, -1].astype(int)
    else:
        from sklearn.datasets import fetch_openml
        d = fetch_openml(name="optdigits", version=1, as_frame=False)
        X = d.data.astype(np.float64)
        y = d.target.astype(int)
    # Optdigits has near-constant pixel columns (corners); the +1e-12
    # guard in _standardize handles the zero-variance ones safely.
    return _standardize(X), y


